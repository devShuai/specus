import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.BreakIterator;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Regenerate the C registration Unicode profile from the project's JDK 21 reference.
 * Development/test tool only; no JVM is required by the C server. No JDK source or
 * implementation rule tables are imported: properties and public boundary behavior
 * are observed at runtime. The legacy cased predicate is queried reflectively, so
 * run with --add-opens java.base/java.lang=ALL-UNNAMED. An incompatible reference
 * must fail rather than silently change the C contract.
 */
public final class GenerateRegistrationUnicode {
    private static final int LETTER=1, NUMBER=2, MARK=4, IGNORE=8, MID_WORD=16,
        MID_NUMBER=32, PRE_NUMBER=64, POST_NUMBER=128, POST_WORD=256,
        CASED=512, WHITE=1024, DOMAIN=2048;

    private static boolean one(BreakIterator iterator,String value) {
        iterator.setText(value);
        return iterator.first()==0 && iterator.next()==value.length() && iterator.next()==BreakIterator.DONE;
    }

    public static void main(String[] args) throws Exception {
        if(Runtime.version().feature()!=21 || args.length!=1) throw new IllegalArgumentException("Use reference JDK 21 and a new output path");
        Path output=Path.of(args[0]);
        if(Files.exists(output)) throw new IllegalArgumentException("Preserve existing generated output");
        var cased=Class.forName("java.lang.ConditionalSpecialCasing").getDeclaredMethod("isCased",int.class);
        cased.setAccessible(true);
        var iterator=BreakIterator.getWordInstance(Locale.ROOT);
        List<int[]> flags=new ArrayList<>(),lower=new ArrayList<>();
        int flagsStart=0,previousFlags=0,lowerStart=-1,previousDelta=0,lowerLast=-1;
        for(int point=0;point<=0x110000;point++) {
            int role=0,delta=0;
            if(point<0x110000 && !(point>=0xd800&&point<=0xdfff)) {
                String scalar=new String(Character.toChars(point));
                int type=Character.getType(point);
                if(type==Character.NON_SPACING_MARK||type==Character.ENCLOSING_MARK) role|=MARK;
                else if(one(iterator,"A-"+scalar+"-A")) role|=LETTER;
                else if(one(iterator,"1,"+scalar+",1")) role|=NUMBER;
                else if(one(iterator,"A"+scalar+"A")&&one(iterator,"1"+scalar+"1")
                    &&one(iterator,scalar+"1")&&one(iterator,"1"+scalar)&&one(iterator,"A"+scalar)) role|=IGNORE;
                else {
                    if(one(iterator,"A"+scalar+"A"))role|=MID_WORD;
                    if(one(iterator,"1"+scalar+"1"))role|=MID_NUMBER;
                    if(one(iterator,scalar+"1"))role|=PRE_NUMBER;
                    if(one(iterator,"1"+scalar))role|=POST_NUMBER;
                    if(one(iterator,"A"+scalar))role|=POST_WORD;
                }
                if((Boolean)cased.invoke(null,point))role|=CASED;
                if(Character.isWhitespace(point))role|=WHITE;
                if(point<=0xffff&&Character.isLetterOrDigit((char)point))role|=DOMAIN;
                if((role&(IGNORE|CASED))==(IGNORE|CASED))throw new IllegalStateException("Ignored cased scalar requires renewed context verification");
                int simple=Character.toLowerCase(point);
                String expected=scalar.toLowerCase(Locale.ROOT);
                if(point!=0x130&&!expected.equals(new String(Character.toChars(simple))))throw new IllegalStateException("New ROOT expansion U+"+Integer.toHexString(point));
                if(expected.length()<scalar.length())throw new IllegalStateException("ROOT UTF-16 contraction requires renewed length handling");
                delta=simple-point;
            }
            if(point==0){previousFlags=role;flagsStart=0;}
            else if(point==0x110000||role!=previousFlags){if(previousFlags!=0)flags.add(new int[]{flagsStart,point-1,previousFlags});flagsStart=point;previousFlags=role;}
            if(delta!=0) {
                if(lowerStart>=0&&(delta!=previousDelta||point!=lowerLast+1)){lower.add(new int[]{lowerStart,lowerLast,previousDelta});lowerStart=-1;}
                if(lowerStart<0){lowerStart=point;previousDelta=delta;}
                lowerLast=point;
            } else if(lowerStart>=0){lower.add(new int[]{lowerStart,lowerLast,previousDelta});lowerStart=-1;}
        }
        StringBuilder text=new StringBuilder("/* Generated by scripts/GenerateRegistrationUnicode.java from reference JDK 21.\n * Observable runtime data, not copied JDK source. Do not edit by hand. */\n#ifndef ST_UNICODE_JAVA21_DATA_H\n#define ST_UNICODE_JAVA21_DATA_H\n\n");
        text.append("typedef struct { uint32_t first, last; uint16_t flags; } st_java21_flag_range;\n");
        text.append("static const st_java21_flag_range st_java21_flags[] = {\n");
        for(int[] row:flags)text.append(String.format(Locale.ROOT,"    {0x%xU, 0x%xU, %dU},\n",row[0],row[1],row[2]));
        text.append("};\n\ntypedef struct { uint32_t first, last; int32_t delta; } st_java21_lower_range;\n");
        text.append("static const st_java21_lower_range st_java21_lower[] = {\n");
        for(int[] row:lower)text.append(String.format(Locale.ROOT,"    {0x%xU, 0x%xU, %d},\n",row[0],row[1],row[2]));
        text.append("};\n\n#endif\n");
        Files.writeString(output,text,StandardCharsets.UTF_8);
        System.out.println("REFERENCE="+Runtime.version()+" FLAGS="+flags.size()+" LOWER_RANGES="+lower.size());
    }
}
