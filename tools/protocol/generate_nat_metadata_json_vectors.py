"""Generates protocol/test-vectors/nat-metadata-json-v1.json.

The NAT_MESSAGE metadata is "a UTF-8 JSON object" (control-protocol.md). Every implementation reads
it strictly by RFC 8259: the whole field is valid UTF-8 and holds exactly one JSON object, with no
comments, trailing commas or anything after it. A field that fails is a malformed body. The cases
are hex so that invalid UTF-8 can be written down; each one is checked against the reference reader
below before the file is written.

Left out on purpose, because RFC 8259 leaves them to the implementation: duplicate names, unpaired
surrogate escapes such as "\\ud800", a byte order mark and nesting depth.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "protocol" / "test-vectors" / "nat-metadata-json-v1.json"


def utf8(text):
    return text.encode("utf-8")


ACCEPTED = [
    ("empty object", utf8("{}")),
    ("an HTTP OPEN", utf8('{"source":"http","phase":"request","method":"GET","route":"web","relativePath":"/"}')),
    ("RFC 8259 whitespace around and inside", utf8(' \t\r\n{ "a" : 1 ,\n"b":[ ] }\r\n ')),
    ("nested values of every kind", utf8('{"a":{"b":[1,2,{"c":null}]},"d":true,"e":false,"f":""}')),
    ("number forms", utf8('{"n":[0,-0,1.5,-2e10,3E+2,4e-3,10]}')),
    ("every escape and a surrogate pair", utf8('{"s":"\\"\\\\\\/\\b\\f\\n\\r\\t\\u00e9\\ud83d\\ude00"}')),
    ("raw multi-byte UTF-8", utf8('{"s":"中文😀"}')),
    ("empty name", utf8('{"":""}')),
]

REJECTED = [
    ("an array", utf8("[]")),
    ("a string", utf8('"x"')),
    ("a number", utf8("1")),
    ("null", utf8("null")),
    ("true", utf8("true")),
    ("whitespace only", utf8("  ")),
    ("unterminated object", utf8('{"a":1')),
    ("trailing comma in an object", utf8('{"a":1,}')),
    ("trailing comma in an array", utf8('{"a":[1,]}')),
    ("content after the object", utf8('{"a":1} x')),
    ("a second object", utf8("{}{}")),
    ("a line comment", utf8("// c\n{}")),
    ("a block comment", utf8('{"a":1/* c */}')),
    ("a hash comment", utf8("# c\n{}")),
    ("single quotes", utf8("{'a':1}")),
    ("an unquoted name", utf8("{a:1}")),
    ("a leading zero", utf8('{"a":01}')),
    ("a plus sign", utf8('{"a":+1}')),
    ("a leading decimal point", utf8('{"a":.5}')),
    ("NaN", utf8('{"a":NaN}')),
    ("Infinity", utf8('{"a":Infinity}')),
    ("a hex number", utf8('{"a":0x1}')),
    ("a raw control character in a string", b'{"a":"\x01"}'),
    ("a raw tab in a string", b'{"a":"\t"}'),
    ("an invalid escape", utf8('{"a":"\\x41"}')),
    ("a byte that is never UTF-8", b'{"a":"\xff"}'),
    ("an overlong encoding", b'{"a":"\xc0\xaf"}'),
    ("a surrogate encoded in UTF-8", b'{"a":"\xed\xa0\x80"}'),
    ("a truncated sequence", b'{"a":"\xe4\xb8"}'),
    ("a lone continuation byte", b'{"a":"\x80"}'),
    ("UTF-16LE", "{}".encode("utf-16-le")),
    ("a vertical tab as whitespace", b"{\x0b}"),
    ("a form feed as whitespace", b"\x0c{}"),
    ("a NUL after the object", b"{}\x00"),
]


def reference_accepts(raw):
    """RFC 8259 with UTF-8 required: Python's decoder refuses overlong forms and surrogates."""
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return False
    if text.startswith("﻿"):
        return False

    def refuse_constant(name):
        raise ValueError(name)

    try:
        value = json.loads(text, parse_constant=refuse_constant)
    except ValueError:
        return False
    return isinstance(value, dict)


def main():
    for name, raw in ACCEPTED:
        assert reference_accepts(raw), f"accepted case is refused by the reference: {name}"
    for name, raw in REJECTED:
        assert not reference_accepts(raw), f"rejected case is accepted by the reference: {name}"
    names = [name for name, _ in ACCEPTED + REJECTED]
    assert len(names) == len(set(names)), "case names must be unique"
    document = {
        "version": 1,
        "description": "NAT_MESSAGE metadata read strictly by RFC 8259 as one UTF-8 JSON object "
                       "(control-protocol.md). A refused case is a malformed body. Generated by "
                       "tools/protocol/generate_nat_metadata_json_vectors.py.",
        "accepted": [{"name": name, "metadataHex": raw.hex()} for name, raw in ACCEPTED],
        "rejected": [{"name": name, "metadataHex": raw.hex()} for name, raw in REJECTED],
    }
    OUTPUT.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(ACCEPTED)} accepted, {len(REJECTED)} rejected")


if __name__ == "__main__":
    main()
